// Regressões de atribuição e contagem, em SQLite na memória; nunca acessa o banco do site.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
import Database from 'better-sqlite3';
const code = ts.transpileModule(readFileSync(new URL('../src/lib/origem.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const { dadosOrigem, agrupar, pago } = await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const d = new Database(':memory:');
d.exec(readFileSync(new URL('../schema.sql',import.meta.url),'utf8'));
d.exec('ALTER TABLE leads ADD COLUMN sessao_id TEXT');
const session=d.prepare(`INSERT INTO sessoes (id,visitante_id,utm_source,utm_medium,utm_campaign,utm_term,utm_content,primeira_pagina,lead_id,robo,clicou_grupo) VALUES (?,?,?,'paid_social',?,?,?,'/black',?,?,?)`);
session.run('a','v1','ig','Campanha A','Conjunto A','AD1',null,0,1);
session.run('b','v2','fb','Campanha A','Conjunto A','AD1',null,0,0);
session.run('c','v3','ig','Campanha B','Conjunto A','AD1',null,0,0);
session.run('bot','bot','ig','Campanha A','Conjunto A','AD1',null,1,1);
const lead=d.prepare(`INSERT INTO leads (nome,whatsapp,utm_source,utm_medium,utm_campaign,utm_term,utm_content,pagina,sessao_id) VALUES ('Teste',?,'ig','paid_social',?,'Conjunto A','AD1','/black',?)`);
lead.run('1','Campanha A','a');lead.run('2','Campanha A','a');lead.run('3','Campanha A',null);lead.run('4','Campanha A','bot');
d.exec("UPDATE sessoes SET lead_id=1 WHERE id='a'; UPDATE sessoes SET lead_id=4 WHERE id='bot'");
const url=(s='')=>new URL('http://localhost/admin/origem?'+s);
let data=dadosOrigem(d,url());
assert.equal(data.total.visitas,3,'Robôs não entram nas visitas');assert.equal(data.total.leads,3,'Cadastros sem sessão entram; os ligados a robô não');assert.equal(data.total.converteu,1,'Vários cadastros não multiplicam a sessão convertida');assert.equal(data.total.abriu,1,'Cadastro implica etapas anteriores');assert.equal(data.total.iniciou,1);
assert.equal(agrupar(data.rows,['campanha','conjunto','anuncio']).length,2,'Anúncios homônimos de campanhas distintas ficam separados');
data=dadosOrigem(d,url('fonte=ig&campanha=Campanha+A&conjunto=Conjunto+A&anuncio=AD1&pagina=/black&canal=pago'));
assert.equal(data.total.visitas,1);assert.equal(data.total.leads,3);assert.equal(data.total.grupo,1);
assert.equal(dadosOrigem(d,url('campanha=inexistente')).rows.length,0);
assert.equal(dadosOrigem(d,url('canal=outro')).total.visitas,0);
assert.equal(dadosOrigem(d,url('dias=invalido')).dias,30);
assert.equal(pago('PAID_SOCIAL'),true);assert.equal(pago('social'),false);
d.exec("UPDATE sessoes SET created_at = strftime('%Y-%m-%dT%H:%M:%fZ','now','-2 days') WHERE id='c'");
assert.equal(dadosOrigem(d,url('dias=1')).total.visitas,2,'Comparação de timestamps ISO respeita as últimas 24h');
session.run('alias','v4','Instagram','Campanha A','Conjunto A','AD1',null,0,0);
assert.equal(agrupar(dadosOrigem(d,url()).rows,['fonte']).find(r=>r.fonte==='ig').visitas,3,'Aliases de Instagram são reunidos');
d.close();console.log('OK: agregação, robôs, filtros, homônimos, cadastros sem sessão e janela de tempo.');
